class ConnectedPlatform(models.Model):
    """Stores OAuth tokens for platforms connected directly by the user"""
    id = models.BigAutoField(primary_key=True)
    creator_id = models.CharField(max_length=255, help_text="User ID from Django frontend")
    platform_name = models.CharField(max_length=50, default="tiktok")
    
    # OAuth tokens
    access_token = models.CharField(max_length=500)
    refresh_token = models.CharField(max_length=500, blank=True, null=True)
    open_id = models.CharField(max_length=255, blank=True, null=True)
    expires_in = models.IntegerField(default=0, help_text="Seconds from when it was saved")
    
    # Audit
    updated_at = models.DateTimeField(auto_now=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "connected_platforms"
        unique_together = ('creator_id', 'platform_name')

    def __str__(self):
        return f"{self.creator_id} - {self.platform_name}"

from django.db import models
from django.conf import settings
import uuid

class TrendingVideo(models.Model):
    """Stores trending TikTok videos scraped by n8n daily (9AM trigger)"""
    id = models.BigAutoField(primary_key=True)
    run_id = models.IntegerField(help_text="The ID of the n8n scraping run")
    rank = models.IntegerField()
    video_id = models.CharField(max_length=255, unique=True)
    title = models.TextField(blank=True, null=True)
    author = models.CharField(max_length=255, blank=True, null=True)
    views = models.CharField(max_length=50, blank=True, null=True)
    likes = models.CharField(max_length=50, blank=True, null=True)
    hashtags = models.TextField(blank=True, null=True, help_text="Stored as string array by N8N")
    category = models.CharField(max_length=100, blank=True, null=True)
    thumbnail_url = models.URLField(max_length=1000, blank=True, null=True)
    tiktok_url = models.URLField(max_length=1000, blank=True, null=True)
    scraped_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "trending_videos"
        ordering = ["-scraped_at", "rank"]

    def __str__(self):
        return f"{self.rank}: {self.title} ({self.video_id})"


class CreatorSession(models.Model):
    """A workflow session triggered when the Creator chooses a trending video and niche"""
    id = models.BigAutoField(primary_key=True)
    session_id = models.CharField(max_length=255, unique=True, help_text="n8n session string like '123_168000000'")
    creator_id = models.CharField(max_length=255, help_text="User ID from Django frontend")
    selected_video_id = models.CharField(max_length=255, help_text="The video_id from trending_videos the creator chose")
    niche = models.CharField(max_length=255, blank=True, null=True)
    platform = models.CharField(max_length=50, default='tiktok', help_text="Platform: tiktok, instagram, facebook, youtube")
    status = models.CharField(max_length=100, default='script_generation')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "creator_sessions"
        ordering = ["-created_at"]

    def __str__(self):
        return f"Session {self.session_id} - {self.niche}"



class FacebookGeneratedVideo(models.Model):
    """Video generated by Facebook N8N workflow (Groq llama-3.3-70b)"""
    reel_id = models.CharField(max_length=255)
    user = models.ForeignKey(settings.AUTH_USER_MODEL, on_delete=models.CASCADE, null=True, blank=True)
    niche = models.CharField(max_length=255, blank=True, null=True)
    user_prompt = models.TextField(blank=True, null=True)

    # Full Groq-generated script (hook + body + cta joined)
    script_content = models.TextField(blank=True, null=True)
    # Raw script JSON from Groq
    script = models.JSONField(blank=True, null=True)
    script_text = models.TextField(blank=True, null=True)  # kept for backward compat

    # Script parts (displayed individually in the app)
    hook = models.TextField(blank=True, null=True)
    body = models.TextField(blank=True, null=True)
    cta = models.TextField(blank=True, null=True)

    # Video generation fields
    hook_text = models.TextField(blank=True, null=True)
    video_prompt = models.TextField(blank=True, null=True)
    negative_prompt = models.TextField(blank=True, null=True)
    caption = models.TextField(blank=True, null=True)
    hashtags = models.TextField(blank=True, null=True)
    music_vibe = models.TextField(blank=True, null=True)
    title = models.TextField(blank=True, null=True)

    video_url = models.URLField(max_length=1000, blank=True, null=True)
    thumbnail_url = models.URLField(max_length=1000, blank=True, null=True)
    status = models.CharField(max_length=50, default='processing')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "facebook_generated_videos"

    def __str__(self):
        return f"{self.reel_id} - {self.niche} - {self.status}"


